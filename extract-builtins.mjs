#!/usr/bin/env node
// Extracts the Wolfram builtin-symbol list out of the extension's own TextMate
// grammar into extension/vendor/wl-builtins.js.
//
//   node extract-builtins.mjs
//
// WHY: telling `Table` and `Integrate` (builtins) apart from `states` and `br`
// (the notebook's own symbols) is the single biggest visual difference between
// crude and proper Wolfram highlighting — and it is exactly what VS Code shows,
// because it uses this same list.
//
// Running the grammar itself in the browser would mean vscode-textmate plus an
// Oniguruma WASM build (~800 KB) to interpret regexes the browser cannot; the
// list is the part that carries the value, and it is a plain data extraction.
//
// The grammar stores them as `System`(?:A(?:bort|bs|bsoluteTiming|…))` — one
// pattern per leading letter, prefix factored out — so reconstruct
// prefix + suffix. Re-run after upgrading the extension.

import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const here = path.dirname(fileURLToPath(import.meta.url));
const GRAMMAR = path.resolve(here, '..', '..', '..',
  'Extension Development', 'syntaxes', 'wolfram.tmLanguage.json');

if (!fs.existsSync(GRAMMAR)) {
  console.error(`grammar not found at ${GRAMMAR}`);
  process.exit(1);
}

const grammar = JSON.parse(fs.readFileSync(GRAMMAR, 'utf8'));
const symbols = new Set();

/** Split on `|` at nesting depth 0. */
function topSplit(s) {
  const parts = [];
  let depth = 0, cur = '';
  for (let i = 0; i < s.length; i++) {
    const ch = s[i];
    if (ch === '\\') { cur += ch + (s[++i] ?? ''); continue; }
    if (ch === '(') depth++;
    else if (ch === ')') depth--;
    else if (ch === '|' && depth === 0) { parts.push(cur); cur = ''; continue; }
    cur += ch;
  }
  parts.push(cur);
  return parts;
}

/**
 * Expand an alternation body into every literal string it can match.
 * Handles `Abs`, `A(?:bs|bort)`, and nesting to any depth. Anything that is not
 * a literal or a (?:…) group (character classes, lookarounds) makes the branch
 * unexpandable, and it is dropped rather than guessed at.
 */
function expandBody(body) {
  const results = [];
  for (const alt of topSplit(body)) {
    let heads = [''];
    let i = 0, bad = false;
    while (i < alt.length) {
      if (alt.startsWith('(?:', i)) {
        // find the matching close paren
        let depth = 0, j = i;
        for (; j < alt.length; j++) {
          if (alt[j] === '\\') { j++; continue; }
          if (alt[j] === '(') depth++;
          else if (alt[j] === ')') { depth--; if (depth === 0) break; }
        }
        if (depth !== 0) { bad = true; break; }
        const inner = expandBody(alt.slice(i + 3, j));
        heads = heads.flatMap((h) => inner.map((t) => h + t));
        i = j + 1;
        continue;
      }
      const ch = alt[i];
      if (/[A-Za-z0-9$]/.test(ch)) { heads = heads.map((h) => h + ch); i++; continue; }
      bad = true; break;                       // (, [, ?, etc — not a plain name
    }
    if (!bad) results.push(...heads);
  }
  return results;
}

for (const pattern of grammar.repository?.symbols?.patterns || []) {
  if (!/builtin/.test(pattern.name || '')) continue;
  let match = pattern.match || '';

  // Strip the trailing word-boundary lookahead, e.g. (?![`$[:alnum:]]) , and the
  // optional System` context prefix. Both appear on every builtin pattern.
  match = match.replace(/\(\?![^)]*\)\s*$/, '').trim();
  match = match.replace(/^System`/, '');

  // What remains is a single (?:…) group.
  const g = match.match(/^\(\?:([\s\S]*)\)$/);
  if (!g) { console.warn('  unparsed pattern:', match.slice(0, 60)); continue; }

  for (const name of expandBody(g[1])) {
    if (/^[A-Z][A-Za-z0-9$]*$/.test(name)) symbols.add(name);
  }
}

const sorted = [...symbols].filter((s) => s.length > 1).sort();
const out = `// wl-builtins.js — AUTO-GENERATED by extract-builtins.mjs from the wolfbook
// extension's wolfram.tmLanguage.json. Do not edit by hand.
//
// Wolfram System\` symbols, used to highlight builtins differently from the
// notebook's own symbols. ${sorted.length} names.
export const WL_BUILTINS = new Set(${JSON.stringify(sorted)});
`;

const dest = path.join(here, 'extension', 'vendor', 'wl-builtins.js');
fs.writeFileSync(dest, out);
console.log(`extension/vendor/wl-builtins.js  ${sorted.length} symbols, ${(out.length / 1024).toFixed(0)} KB`);
console.log('  spot check:', ['Table', 'Integrate', 'NestWhileList', 'Plot3D', 'EigenSystem', 'Module']
  .map((s) => `${s}=${symbols.has(s)}`).join(' '));
